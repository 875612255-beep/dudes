fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .expect("workspace root")
}

fn collect_files(base: &Path, dir: &Path, found: &mut Vec<String>) {
    for entry in fs::read_dir(dir).expect("read vendor directory") {
        let path = entry.expect("vendor entry").path();
        if path.is_dir() {
            collect_files(base, &path, found);
        } else {
            found.push(
                path.strip_prefix(base)
                    .expect("vendor relative path")
                    .to_string_lossy()
                    .replace('\\', "/"),
            );
        }
    }
}

fn normalized(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

#[test]
fn vendor_is_exactly_the_reviewed_candidate_plus_provenance() {
    let vendor = root().join("vendor/libproc");
    let mut found = Vec::new();
    collect_files(&vendor, &vendor, &mut found);
    found.sort();

    let mut expected: Vec<_> = CANDIDATE_PATHS.iter().map(ToString::to_string).collect();
    expected.push("PROVENANCE.md".to_owned());
    expected.sort();
    assert_eq!(
        found, expected,
        "the vendor tree is 33 reviewed files plus provenance"
    );
}

#[test]
fn vendor_and_notices_exclude_generated_or_sdk_material() {
    let root = root();
    let vendor = root.join("vendor/libproc");
    let mut found = Vec::new();
    collect_files(&vendor, &vendor, &mut found);
    let bindgen_marker = ["automatically generated by rust-", "bindgen"].concat();
    for path in &found {
        let extension = Path::new(path).extension();
        assert_ne!(path, "docs_rs/osx_libproc_bindings.rs");
        assert!(
            !extension.is_some_and(|extension| extension.eq_ignore_ascii_case("h")),
            "SDK header in vendor: {path}"
        );
        assert!(
            !extension.is_some_and(|extension| extension.eq_ignore_ascii_case("dylib")),
            "dynamic library in vendor: {path}"
        );
        assert!(
            !path
                .split('/')
                .any(|part| part == "target" || part == "OUT_DIR"),
            "build output in vendor: {path}"
        );
        let bytes = fs::read(vendor.join(path)).expect("read vendored file");
        assert!(
            !bytes
                .windows(bindgen_marker.len())
                .any(|window| window == bindgen_marker.as_bytes()),
            "pregenerated binding marker in {path}"
        );
    }

    let provenance = fs::read_to_string(vendor.join("PROVENANCE.md")).expect("provenance");
    for required in [
        "10e18c6933887aea43de06ebefa447233fa808a3",
        "929145db466dc268df0acd8fc55b4ef4d87dc60f",
        "a832b6419414b2eabbaff05a0e88133e7e0f9607830e0238c9eee252f9461394",
        "1d3684659abc02c544b902e2c50bc631aee98517d512abc1af8f6609cd607524",
        "docs_rs/osx_libproc_bindings.rs",
    ] {
        assert!(
            provenance.contains(required),
            "provenance lost `{required}`"
        );
    }

    let license = fs::read_to_string(vendor.join("LICENSE")).expect("vendor license");
    let recipient = fs::read_to_string(root.join("THIRD-PARTY.md")).expect("recipient notice");
    assert!(
        normalized(&recipient).contains(&normalized(&license)),
        "the recipient notice must carry the complete upstream MIT text"
    );
}

#[test]
fn workspace_and_reuse_metadata_keep_the_vendor_separate_and_mit() {
    let root = root();
    let manifest = fs::read_to_string(root.join("Cargo.toml")).expect("root manifest");
    assert!(manifest.contains("exclude = [\"fuzz\", \"vendor/libproc\"]"));
    assert!(manifest.contains("libproc = { path = \"vendor/libproc\" }"));

    let host =
        fs::read_to_string(root.join("crates/dudes-host/Cargo.toml")).expect("host manifest");
    assert!(host.contains("publish = false"));

    let reuse = fs::read_to_string(root.join("REUSE.toml")).expect("REUSE metadata");
    for required in [
        "path = [\"vendor/libproc/**\"]",
        "2010 3scale networks S.L.",
        "2026 The Dudes contributors",
        "SPDX-License-Identifier = \"MIT\"",
        "vendor/libproc/PROVENANCE.md",
    ] {
        assert!(reuse.contains(required), "REUSE metadata lost `{required}`");
    }
}
